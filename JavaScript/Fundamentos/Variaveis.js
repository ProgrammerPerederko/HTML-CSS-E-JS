// Variaveis - Introdução

/* 
O que variaveis?

Tipos de variáveis

- String - Texto Caracteres
- Number - Inteiros 
- Boolean - True ou False

Regras para Declaração de Variáveis:

 - Não podem ser iniciadas com números, apenas com letras ou "_"
 - Não podem ser ultilizados caracteres especiais como "ç", "^", "~"
 - Não podem ser iguais as palavras reservados na linguagem
 - Sempre  usar ; no final de cada comando

 Declarando variaveis com Let:

 Case Sensitive:
 
 let curso, let Curso, let CURSO.

 Exemplos:
*/


// String
let texto = "String";

// Number
let numeroInteiro = 10;
let numeroFracionado = 11210.75;

// boolean
let Temdinheiro = false; //true  -> verdadeiro / false -> falso 

//null
let valorNull = null;

//undefined
let valorUndefined;

// Alterado valores de variaveis

valorUndefined = "Valor"

console.log(valorUndefined)